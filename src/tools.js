/**
 * The Pipefetch MCP server: seven tools that give an AI assistant YouTube transcripts, video details,
 * channels, search results and comments through the Pipefetch API (https://pipefetch.com).
 */
import { McpServer } from '@modelcontextprotocol/server';
import Pipefetch, { PipefetchError } from 'pipefetch';
import * as z from 'zod/v4';

export const VERSION = '0.1.0';

const video = z.string().describe('A YouTube video ID or any YouTube video URL.');
const channel = z.string().describe('A channel handle (@mkbhd), a channel ID (UC...) or any channel URL.');
/** These tools only read public data and reach out to the internet. */
const annotations = { readOnlyHint: true, openWorldHint: true };

const seconds = (total) => (typeof total === 'number' ? `${Math.floor(total / 60)}:${String(Math.round(total % 60)).padStart(2, '0')}` : 'unknown');

/** A transcript as text a model can read straight away, with what it needs to cite the video. */
function transcriptText(data) {
  const lines = [
    `Title: ${data.title ?? 'unknown'}`,
    `Channel: ${data.channel?.name ?? 'unknown'}`,
    `URL: ${data.url}`,
    `Length: ${seconds(data.durationSeconds)}`,
    `Language: ${data.languageName ?? data.language}${data.isAutoGenerated ? ' (auto-generated captions)' : ''}`,
  ];
  if (Array.isArray(data.chapters) && data.chapters.length > 0) {
    lines.push(`Chapters: ${data.chapters.map((c) => `${seconds(c.startSeconds)} ${c.title}`).join('; ')}`);
  }
  return `${lines.join('\n')}\n\n${data.text}`;
}

/**
 * @param {Record<string, string | undefined>} [env] Where PIPEFETCH_API_KEY (and, for tests, PIPEFETCH_BASE_URL) are read from.
 */
export function buildServer(env = process.env) {
  const server = new McpServer({ name: 'pipefetch', version: VERSION });

  // The client is created on first use, so the server starts and lists its tools without a key.
  let client;
  const pipefetch = () => {
    if (!env.PIPEFETCH_API_KEY) {
      throw new PipefetchError(
        'No Pipefetch API key is set. Add PIPEFETCH_API_KEY to this MCP server\'s configuration. A key with 100 free credits is at https://pipefetch.com/dashboard',
      );
    }
    client ??= new Pipefetch({ apiKey: env.PIPEFETCH_API_KEY, baseUrl: env.PIPEFETCH_BASE_URL || undefined });
    return client;
  };

  /** Run one API call and turn its answer, or its error, into a tool result. */
  const answer = async (call, render = (data) => JSON.stringify(data, null, 2)) => {
    try {
      return { content: [{ type: 'text', text: render(await call(pipefetch())) }] };
    } catch (error) {
      const text = error instanceof PipefetchError
        ? `${error.message}${error.code ? ` (${error.code})` : ''}`
        : `Unexpected error: ${error?.message ?? error}`;
      return { content: [{ type: 'text', text }], isError: true };
    }
  };

  server.registerTool(
    'youtube_transcript',
    {
      title: 'YouTube transcript',
      description:
        'Get the transcript (captions) of a public YouTube video as text, with its title, channel, length and chapters. Use it to read, summarize or quote what is said in a video. Costs 1 Pipefetch credit; a video without captions costs nothing.',
      inputSchema: z.object({
        video,
        lang: z.string().optional().describe('Preferred caption language code, such as "en" or "pt-BR". Without it you get the video\'s original language.'),
        timestamps: z.boolean().optional().describe('Put a time marker such as [0:12] in front of each line, to point at moments in the video.'),
      }),
      annotations,
    },
    ({ video: id, lang, timestamps }) =>
      answer((pf) => pf.transcript(id, { lang, format: timestamps ? 'timestamped' : 'text', segments: false }), transcriptText),
  );

  server.registerTool(
    'youtube_video',
    {
      title: 'YouTube video details',
      description:
        'Get the details of one public YouTube video: exact view, like and comment counts, description, publish date, duration, tags, chapters and channel. Costs 1 Pipefetch credit.',
      inputSchema: z.object({ video }),
      annotations,
    },
    ({ video: id }) => answer((pf) => pf.video(id)),
  );

  server.registerTool(
    'youtube_channel',
    {
      title: 'YouTube channel details',
      description: 'Get a YouTube channel\'s subscriber count, video count, description, keywords and avatar. Costs 1 Pipefetch credit.',
      inputSchema: z.object({ channel }),
      annotations,
    },
    ({ channel: ref }) => answer((pf) => pf.channel(ref)),
  );

  server.registerTool(
    'youtube_channel_videos',
    {
      title: 'Latest videos of a YouTube channel',
      description:
        'List the latest uploads of a YouTube channel, newest first, with views, duration and publish time, plus the channel\'s own details. Returns at most 30 and cannot go further back. Costs 1 Pipefetch credit.',
      inputSchema: z.object({ channel, limit: z.number().int().min(1).max(30).optional().describe('How many of the latest uploads to return: 1 to 30. Default 30.') }),
      annotations,
    },
    ({ channel: ref, limit }) => answer((pf) => pf.channelVideos(ref, { limit })),
  );

  server.registerTool(
    'youtube_channel_shorts',
    {
      title: 'Latest Shorts of a YouTube channel',
      description: 'List the latest Shorts of a YouTube channel, newest first, with view counts. Returns at most 40. Costs 1 Pipefetch credit; a channel without Shorts costs nothing.',
      inputSchema: z.object({ channel, limit: z.number().int().min(1).max(40).optional().describe('How many of the latest Shorts to return: 1 to 40. Default 20.') }),
      annotations,
    },
    ({ channel: ref, limit }) => answer((pf) => pf.channelShorts(ref, { limit })),
  );

  server.registerTool(
    'youtube_search',
    {
      title: 'Search YouTube',
      description:
        'Search YouTube and get the results with titles, channels, view counts, durations and publish times. Returns at most 40 results and has no further pages. Costs 1 Pipefetch credit; a search without results costs nothing.',
      inputSchema: z.object({
        query: z.string().describe('What to search for.'),
        limit: z.number().int().min(1).max(40).optional().describe('How many results to return: 1 to 40. Default 20.'),
        type: z.enum(['video', 'short', 'channel', 'playlist', 'all']).optional().describe('Kind of result. Default "video".'),
        sort: z.enum(['relevance', 'popularity', 'newest', 'mostViewed']).optional().describe('Result order. Default "relevance".'),
        uploaded: z.enum(['hour', 'today', 'week', 'month', 'year']).optional().describe('Only results uploaded within this period.'),
        country: z.string().optional().describe('Two-letter country code the search is run for, such as "US".'),
        lang: z.string().optional().describe('Interface language code for titles and labels, such as "en".'),
      }),
      annotations,
    },
    ({ query, ...options }) => answer((pf) => pf.search(query, options)),
  );

  server.registerTool(
    'youtube_comments',
    {
      title: 'YouTube comments',
      description:
        'Get the top or the newest comments of a public YouTube video, with likes, reply counts and authors\' public names. Returns at most 100 top-level comments. Costs 1 Pipefetch credit per started 20 comments; a video with comments turned off costs nothing.',
      inputSchema: z.object({
        video,
        limit: z.number().int().min(1).max(100).optional().describe('How many comments to return: 1 to 100. Default 20. Every started 20 cost 1 credit.'),
        sort: z.enum(['top', 'newest']).optional().describe('Top comments first, or newest first. Default "top".'),
      }),
      annotations,
    },
    ({ video: id, limit, sort }) => answer((pf) => pf.comments(id, { limit, sort })),
  );

  return server;
}
