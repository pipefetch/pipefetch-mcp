import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const serverFile = fileURLToPath(new URL('../src/server.js', import.meta.url));

/** A stand-in for the Pipefetch API that records what it was asked. */
async function fakeApi() {
  const asked = [];
  const http = createServer((req, res) => {
    const url = new URL(req.url, 'http://x');
    asked.push({ path: url.pathname, query: Object.fromEntries(url.searchParams), key: req.headers['x-api-key'] });
    const send = (status, body) => {
      res.writeHead(status, { 'content-type': 'application/json' });
      res.end(JSON.stringify(body));
    };
    if (url.pathname === '/v1/youtube/transcript' && url.searchParams.get('video') === 'nocaptions00') {
      return send(404, { error: { code: 'no_transcript', message: 'This video has no captions. Nothing was charged.' } });
    }
    if (url.pathname === '/v1/youtube/transcript') {
      return send(200, {
        data: {
          videoId: 'jNQXAC9IVRw', url: 'https://www.youtube.com/watch?v=jNQXAC9IVRw', title: 'Me at the zoo', channel: { name: 'jawed' },
          durationSeconds: 19, language: 'en', languageName: 'English', isAutoGenerated: false, text: 'All right, so here we are, in front of the elephants',
          chapters: [{ title: 'Intro', startSeconds: 0, endSeconds: 5 }],
        },
        credits: { used: 1, remaining: 99 },
      });
    }
    return send(200, { data: { query: url.searchParams.get('q'), results: [{ title: 'A result', viewCount: 7 }] }, credits: { used: 1, remaining: 98 } });
  });
  await new Promise((resolve) => http.listen(0, '127.0.0.1', resolve));
  return { asked, url: `http://127.0.0.1:${http.address().port}`, close: () => new Promise((resolve) => http.close(resolve)) };
}

/** Start the server as an MCP client would, and talk to it in newline-delimited JSON-RPC. */
function startServer(env) {
  const child = spawn(process.execPath, [serverFile], { env: { ...process.env, PIPEFETCH_API_KEY: '', PIPEFETCH_BASE_URL: '', ...env }, stdio: ['pipe', 'pipe', 'pipe'] });
  const waiting = new Map();
  let buffer = '';
  let stderr = '';
  child.stderr.on('data', (chunk) => { stderr += chunk; });
  child.stdout.on('data', (chunk) => {
    buffer += chunk;
    let newline;
    while ((newline = buffer.indexOf('\n')) >= 0) {
      const line = buffer.slice(0, newline).trim();
      buffer = buffer.slice(newline + 1);
      if (!line) continue;
      const message = JSON.parse(line);
      if (message.id !== undefined && waiting.has(message.id)) {
        waiting.get(message.id)(message);
        waiting.delete(message.id);
      }
    }
  });
  let nextId = 1;
  const send = (message) => child.stdin.write(JSON.stringify(message) + '\n');
  const request = (method, params) => {
    const id = nextId++;
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error(`No answer to ${method}. Server said: ${stderr}`)), 10_000);
      waiting.set(id, (message) => {
        clearTimeout(timer);
        resolve(message);
      });
      send({ jsonrpc: '2.0', id, method, ...(params ? { params } : {}) });
    });
  };
  return {
    request,
    async handshake() {
      const hello = await request('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'test', version: '0' } });
      send({ jsonrpc: '2.0', method: 'notifications/initialized' });
      return hello;
    },
    stop: () => child.kill(),
  };
}

test('the server introduces itself and lists its seven tools, also without an API key', async () => {
  const server = startServer({});
  try {
    const hello = await server.handshake();
    assert.equal(hello.result.serverInfo.name, 'pipefetch');
    const { result } = await server.request('tools/list');
    assert.deepEqual(
      result.tools.map((tool) => tool.name).sort(),
      ['youtube_channel', 'youtube_channel_shorts', 'youtube_channel_videos', 'youtube_comments', 'youtube_search', 'youtube_transcript', 'youtube_video'],
    );
    for (const tool of result.tools) {
      assert.ok(tool.description.includes('credit'), `${tool.name} says what it costs`);
      assert.equal(tool.inputSchema.type, 'object');
      assert.ok(tool.inputSchema.required.length >= 1, `${tool.name} has a required input`);
    }
    const search = result.tools.find((tool) => tool.name === 'youtube_search');
    assert.deepEqual(search.inputSchema.required, ['query']);
    assert.deepEqual(search.inputSchema.properties.sort.enum, ['relevance', 'popularity', 'newest', 'mostViewed']);
    assert.equal(search.title, 'Search YouTube');
    assert.equal(search.annotations.readOnlyHint, true);

    // Without a key a call explains what to do, as an error result, not as a crash.
    const call = await server.request('tools/call', { name: 'youtube_video', arguments: { video: 'jNQXAC9IVRw' } });
    assert.equal(call.result.isError, true);
    assert.match(call.result.content[0].text, /PIPEFETCH_API_KEY/);
  } finally {
    server.stop();
  }
});

test('tools call the API with the key and hand back readable answers and errors', async () => {
  const api = await fakeApi();
  const server = startServer({ PIPEFETCH_API_KEY: 'pf_test', PIPEFETCH_BASE_URL: api.url });
  try {
    await server.handshake();

    const transcript = await server.request('tools/call', { name: 'youtube_transcript', arguments: { video: 'https://youtu.be/jNQXAC9IVRw', timestamps: true } });
    assert.notEqual(transcript.result.isError, true);
    const text = transcript.result.content[0].text;
    assert.match(text, /^Title: Me at the zoo\nChannel: jawed\n/);
    assert.match(text, /Length: 0:19/);
    assert.match(text, /Chapters: 0:00 Intro/);
    assert.match(text, /in front of the elephants$/);
    assert.deepEqual(api.asked[0], { path: '/v1/youtube/transcript', query: { video: 'https://youtu.be/jNQXAC9IVRw', format: 'timestamped', segments: 'false' }, key: 'pf_test' });

    const missing = await server.request('tools/call', { name: 'youtube_transcript', arguments: { video: 'nocaptions00' } });
    assert.equal(missing.result.isError, true);
    assert.equal(missing.result.content[0].text, 'This video has no captions. Nothing was charged. (no_transcript)');

    const search = await server.request('tools/call', { name: 'youtube_search', arguments: { query: 'web scraping', sort: 'newest', limit: 5 } });
    assert.deepEqual(JSON.parse(search.result.content[0].text), { query: 'web scraping', results: [{ title: 'A result', viewCount: 7 }] });
    assert.deepEqual(api.asked.at(-1), { path: '/v1/youtube/search', query: { q: 'web scraping', sort: 'newest', limit: '5' }, key: 'pf_test' });

    // An input that breaks the tool's rules never reaches the API.
    const before = api.asked.length;
    const bad = await server.request('tools/call', { name: 'youtube_comments', arguments: { video: 'jNQXAC9IVRw', limit: 500 } });
    assert.ok(bad.error || bad.result.isError, 'a limit of 500 is refused');
    assert.equal(api.asked.length, before);
  } finally {
    server.stop();
    await api.close();
  }
});
